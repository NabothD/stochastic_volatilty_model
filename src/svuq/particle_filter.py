"""Vectorised particle filter (SIR) for the latent variance and jumps.

Compared with the original scripts this implementation

* is fully vectorised over particles (the old Heston filter looped over every
  particle in pure Python, which dominated run time);
* uses each return exactly once and with the right timing: ``R_k`` is
  generated by ``V_{k-1}``, so particles of ``V_{k-1}`` are *weighted* by
  ``p(R_k | V_{k-1})`` and then *propagated* to ``V_k`` with the variance
  shock correlated to the price shock implied by ``R_k``.  The old code
  propagated with ``R_k`` and then re-weighted the propagated particle with
  the same ``R_k``, double-counting that observation;
* re-initialises the particle cloud at t=0 on every Gibbs sweep (previously the
  cloud from the *end* of the previous sweep was reused as the t=0 cloud);
* for Bates, keeps ``(V, J, Z)`` together when resampling (the old code
  resampled ``V`` and ``Z`` independently, destroying the pairing), uses the
  per-step jump probability ``lam*dt`` instead of the fixed initial ``lam``,
  and proposes jump sizes from a return-informed Gaussian so that the few
  particles that do jump land near the observed jump (importance weights
  are corrected exactly).
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Optional

import numpy as np

from .models import HestonParams

_V_FLOOR = 1e-10
_LOG2PI = np.log(2.0 * np.pi)


# ----------------------------------------------------------------------------
# Resampling
# ----------------------------------------------------------------------------
def systematic_resample(w: np.ndarray, rng: np.random.Generator) -> np.ndarray:
    n = w.size
    u = (np.arange(n) + rng.random()) / n
    idx = np.searchsorted(np.cumsum(w), u)
    return np.minimum(idx, n - 1)


def smooth_resample(x: np.ndarray, w: np.ndarray, rng: np.random.Generator):
    """Continuous ("refined") resampling of a scalar state, thesis Eqs. 67–73.

    The particles are sorted and the empirical CDF is replaced by a piecewise
    linear one with knots ``F(x_(0)) = 0``, ``F(x_(i)) = sum_{l<i} w_l + w_i/2``
    and ``F(x_(N-1)) = 1``; stratified uniforms are pushed through its inverse.
    Unlike multinomial resampling, the output is a continuous function of the
    weights (Malik & Pitt 2011), which reduces Monte-Carlo noise in the
    parameter updates.

    Returns ``(x_new, idx)`` where ``idx`` is the index (in the *original*
    ordering) of the bracketing particle each new value was interpolated
    towards, so that auxiliary variables (jumps) can be carried along.
    """
    n = x.size
    order = np.argsort(x, kind="stable")
    xs, ws = x[order], w[order]
    knots = np.cumsum(ws) - 0.5 * ws
    knots[0] = 0.0
    knots[-1] = 1.0
    np.maximum.accumulate(knots, out=knots)
    u = (np.arange(n) + rng.random(n)) / n
    j = np.clip(np.searchsorted(knots, u, side="right") - 1, 0, n - 2)
    width = knots[j + 1] - knots[j]
    frac = np.where(width > 0, (u - knots[j]) / np.where(width > 0, width, 1.0), 0.0)
    frac = np.clip(frac, 0.0, 1.0)
    x_new = xs[j] + frac * (xs[j + 1] - xs[j])
    pick_right = rng.random(n) < frac
    idx = order[np.where(pick_right, j + 1, j)]
    return x_new, idx


# ----------------------------------------------------------------------------
# Filter
# ----------------------------------------------------------------------------
@dataclass
class FilterResult:
    v_mean: np.ndarray            # E[V_k | R_1..R_k], k = 0..n
    v_sd: np.ndarray              # sd of the filtered cloud
    loglik: float                 # log p(R_1..R_n | params) (particle estimate)
    ess: np.ndarray               # effective sample size before each resampling
    jump_prob: np.ndarray         # P(J_k = 1 | R_1..R_k), k = 1..n
    jump_size_mean: np.ndarray    # E[Z_k | J_k = 1, R_1..R_k]
    jump_size_m2: np.ndarray      # E[Z_k^2 | J_k = 1, R_1..R_k]
    jump_draw: np.ndarray         # one draw of J_k from the filter
    size_draw: np.ndarray         # one draw of Z_k (meaningful where jump_draw==1)
    cloud: Optional[np.ndarray]   # (n+1, N) equally weighted filtered particles (if stored)


def _initial_particles(params: HestonParams, n: int, rng: np.random.Generator,
                       v0_mean: Optional[float], v0_sd: Optional[float]) -> np.ndarray:
    if v0_mean is not None and v0_sd is not None and v0_sd > 0:
        shape = (v0_mean / v0_sd) ** 2
        return rng.gamma(shape, v0_mean / shape, n)
    # stationary distribution of the CIR process
    shape = min(2.0 * params.kappa * params.theta / params.sigma ** 2, 1e6)
    return rng.gamma(shape, params.theta / shape, n)


def run_filter(
    R: np.ndarray,
    params: HestonParams,
    dt: float,
    n_particles: int = 1000,
    rng: Optional[np.random.Generator] = None,
    resampling: str = "smooth",
    jump_proposal_prob: float = 0.1,
    store_cloud: bool = False,
    v0_mean: Optional[float] = None,
    v0_sd: Optional[float] = None,
) -> FilterResult:
    """Run the SIR filter over gross returns ``R`` for the given parameters.

    ``params`` may be :class:`HestonParams` (no jumps) or :class:`BatesParams`.
    ``resampling`` is ``"smooth"`` (thesis' refined resampling) or ``"systematic"``.
    """
    if resampling not in ("smooth", "systematic"):
        raise ValueError("resampling must be 'smooth' or 'systematic'")
    rng = rng if rng is not None else np.random.default_rng()
    n, N = R.size, n_particles
    mu, kappa, theta, sigma, rho = params.mu, params.kappa, params.theta, params.sigma, params.rho
    rho_c = np.sqrt(max(1.0 - rho ** 2, 1e-12))
    drift = 1.0 + mu * dt
    p_jump = min(params.lam * dt, 0.999)
    has_jumps = p_jump > 0.0
    q_jump = max(p_jump, jump_proposal_prob) if has_jumps else 0.0
    sj = max(params.sigma_j, 1e-8)

    V = np.maximum(_initial_particles(params, N, rng, v0_mean, v0_sd), _V_FLOOR)
    v_mean = np.empty(n + 1)
    v_sd = np.empty(n + 1)
    v_mean[0], v_sd[0] = V.mean(), V.std()
    ess = np.empty(n)
    jump_prob = np.zeros(n)
    jump_size_mean = np.full(n, params.mu_j)
    jump_size_m2 = np.full(n, params.mu_j ** 2 + params.sigma_j ** 2)
    jump_draw = np.zeros(n, dtype=int)
    size_draw = np.zeros(n)
    cloud = np.empty((n + 1, N)) if store_cloud else None
    if store_cloud:
        cloud[0] = V
    loglik = 0.0
    zeros = np.zeros(N)

    for k in range(n):
        r = R[k]
        var = V * dt
        if has_jumps:
            J = rng.random(N) < q_jump
            # return-informed Gaussian proposal for the jump size
            y = np.log(r / drift)
            prec = 1.0 / sj ** 2 + 1.0 / var
            m_q = (params.mu_j / sj ** 2 + y / var) / prec
            s_q = 1.5 / np.sqrt(prec)
            Z = np.where(J, m_q + s_q * rng.standard_normal(N), 0.0)
            eZ = np.exp(Z)
            # log p(R | V, J, Z)
            lw = -0.5 * (_LOG2PI + np.log(eZ ** 2 * var)) - 0.5 * (r - eZ * drift) ** 2 / (eZ ** 2 * var)
            lw += np.where(
                J,
                np.log(p_jump / q_jump)
                - 0.5 * ((Z - params.mu_j) / sj) ** 2 - np.log(sj)
                + 0.5 * ((Z - m_q) / s_q) ** 2 + np.log(s_q),
                np.log((1.0 - p_jump) / (1.0 - q_jump)),
            )
        else:
            J, Z, eZ = zeros, zeros, 1.0
            lw = -0.5 * (_LOG2PI + np.log(var)) - 0.5 * (r - drift) ** 2 / var

        m = lw.max()
        w = np.exp(lw - m)
        sw = w.sum()
        loglik += m + np.log(sw / N)
        w /= sw
        ess[k] = 1.0 / (w @ w)

        if has_jumps:
            pj = float(w @ J)
            jump_prob[k] = pj
            if pj > 1e-300:
                jump_size_mean[k] = float((w * J) @ Z) / pj
                jump_size_m2[k] = float((w * J) @ (Z * Z)) / pj
            pick = min(np.searchsorted(np.cumsum(w), rng.random()), N - 1)
            jump_draw[k] = int(J[pick])
            size_draw[k] = Z[pick] if J[pick] else rng.normal(params.mu_j, sj)

        # resample (V_{k-1}, J_k, Z_k) jointly
        if resampling == "smooth":
            V, idx = smooth_resample(V, w, rng)
        else:
            idx = systematic_resample(w, rng)
            V = V[idx]
        if has_jumps:
            Zr = Z[idx]
            r_adj = r * np.exp(-Zr)
        else:
            r_adj = r

        # propagate to V_k with the price shock implied by R_k
        sq = np.sqrt(V * dt)
        eps_s = (r_adj - drift) / sq
        eps_v = rho * eps_s + rho_c * rng.standard_normal(N)
        V = np.maximum(V + kappa * (theta - V) * dt + sigma * sq * eps_v, _V_FLOOR)

        v_mean[k + 1] = V.mean()
        v_sd[k + 1] = V.std()
        if store_cloud:
            cloud[k + 1] = V

    return FilterResult(v_mean, v_sd, float(loglik), ess, jump_prob, jump_size_mean,
                        jump_size_m2, jump_draw, size_draw, cloud)


def backward_sample(cloud: np.ndarray, R_adj: np.ndarray, params: HestonParams, dt: float,
                    rng: np.random.Generator) -> np.ndarray:
    """Forward-filter backward-sample one variance trajectory ``V_0..V_n``.

    ``cloud[k]`` are equally weighted draws from ``p(V_k | R_1..R_k)`` and
    ``R_adj`` are the returns with the sampled jumps removed.  Backward weights
    are ``p(R_{k+1} | V_k) * p(V_{k+1} | V_k, R_{k+1})``, both Gaussian under the
    Euler scheme.  The resulting path is a draw from (an approximation of) the
    *smoothing* distribution, so the Gibbs updates see realistic variance
    increments rather than the over-smooth filtered mean.
    """
    n = R_adj.size
    mu, kappa, theta, sigma, rho = params.mu, params.kappa, params.theta, params.sigma, params.rho
    rho_c2 = max(1.0 - rho ** 2, 1e-12)
    drift = 1.0 + mu * dt
    path = np.empty(n + 1)
    path[n] = cloud[n, rng.integers(cloud.shape[1])]
    for k in range(n - 1, -1, -1):
        V = cloud[k]
        var = V * dt
        eps_s = (R_adj[k] - drift) / np.sqrt(var)
        mean_next = V + kappa * (theta - V) * dt + sigma * np.sqrt(var) * rho * eps_s
        var_next = sigma ** 2 * var * rho_c2
        lw = (-0.5 * np.log(var) - 0.5 * eps_s ** 2
              - 0.5 * np.log(var_next) - 0.5 * (path[k + 1] - mean_next) ** 2 / var_next)
        w = np.exp(lw - lw.max())
        w /= w.sum()
        path[k] = V[min(np.searchsorted(np.cumsum(w), rng.random()), V.size - 1)]
    return path
